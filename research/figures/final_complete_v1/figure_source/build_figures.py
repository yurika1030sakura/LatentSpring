def make_fig2():
    # Each plot is authored independently; two vector plots are then assembled.
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    from matplotlib.patches import Patch
    plt.rcParams.update({'font.family':'DejaVu Sans','font.size':8.5,'axes.labelsize':8.5,'xtick.labelsize':8,'ytick.labelsize':8.5,'pdf.fonttype':42,'svg.fonttype':'none'})
    series=json.loads((ROOT/'data/figure2_plot_data.json').read_text())
    paneldir=ROOT/'panels';paneldir.mkdir(exist_ok=True)
    fig=plt.figure(figsize=(3.10,2.72));ax=fig.add_axes([.33,.24,.65,.63]);ax.spines[['top','right','left']].set_visible(False)
    for i,row in enumerate(series):
        y=(3-i)*2.8
        bars=ax.barh([y+.43,y-.43],[row['graph'],row['graph_force']],height=.68,color=METHOD_COLORS[row['method']])
        bars[0].set_alpha(.28)
        for p,val in zip(bars,[row['graph'],row['graph_force']]):
            ax.text(val+.75,p.get_y()+p.get_height()/2,f'{val:.2f}',fontsize=8,va='center')
    ax.set_yticks([i*2.8 for i in range(4)],[r['method'] for r in series[::-1]])
    ax.set_xlim(0,46);ax.set_ylim(-1.25,9.8);ax.set_xticks([0,20,40]);ax.tick_params(axis='y',length=0,pad=5)
    ax.grid(axis='x',alpha=.18,linewidth=.5);ax.set_axisbelow(True);ax.set_xlabel('All generation attempts (%)',labelpad=5)
    fig.text(.03,.947,'a  Graph and force',fontsize=10,fontweight='bold')
    # Two independent legend samples encode opacity rather than a new data series.


    for ext in ['svg','pdf']:fig.savefig(paneldir/('main_left.'+ext))
    plt.close(fig)
    fig=plt.figure(figsize=(2.40,2.72));ax=fig.add_axes([.27,.24,.68,.63]);ax.spines[['top','right']].set_visible(False)
