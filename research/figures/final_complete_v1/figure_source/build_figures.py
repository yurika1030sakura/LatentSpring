def text(x,y,content,size=8.5,weight='normal',anchor='start',fill=INK):
    return f'<text x="{x}" y="{y}" font-family="DejaVu Sans" font-size="{size}" font-weight="{weight}" text-anchor="{anchor}" fill="{fill}">{content}</text>'

def math_svg(expression,x,y,size=9.0):
    from matplotlib.mathtext import math_to_image
    from matplotlib import rc_context
    from matplotlib.font_manager import FontProperties
    b=io.BytesIO()
    with rc_context({'mathtext.fontset':'dejavusans','svg.fonttype':'path'}):
        math_to_image('$'+expression+'$',b,prop=FontProperties(size=size),format='svg',color=INK)
    e=E.fromstring(b.getvalue())
    for g in e.xpath("//*[@id='patch_1']"):
        g.getparent().remove(g)
    w=float(e.attrib['width'].replace('pt',''));h=float(e.attrib['height'].replace('pt',''))
    e.attrib.update(dict(x=str(x),y=str(y),width=str(w),height=str(h)))
    # IDs generated by mathtext can repeat across independent equations.
    serial=f'm{int(x*100)}_{int(y*100)}_'
    raw=E.tostring(e).decode();ids=re.findall(r'id="([^"]+)"',raw)
    for i in ids:raw=raw.replace(f'id="{i}"',f'id="{serial+i}"').replace(f'#{i}"',f'#{serial+i}"').replace(f'#{i})',f'#{serial+i})')
    return raw

def img(path,x,y,w,h):
    b=base64.b64encode(Path(path).read_bytes()).decode()
    return f'<image x="{x}" y="{y}" width="{w}" height="{h}" href="data:image/png;base64,{b}"/>'

def rect(x,y,w,h,fill,stroke='none',rx=5):
    return f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="{rx}" fill="{fill}" stroke="{stroke}" stroke-width="0.6"/>'

def arrow(x1,y1,x2,y2):
    return f'<path d="M {x1} {y1} L {x2} {y2}" stroke="{SUB}" stroke-width="1.1" fill="none" marker-end="url(#arrow)"/>'

def export_svg(svg,path):
    path.write_text(svg)
    cairosvg.svg2pdf(url=str(path),write_to=str(path.with_suffix('.pdf')))
    # Rasterize the finished PDF: preview and publication PDF cannot drift.
    d=fitz.open(path.with_suffix('.pdf'));d[0].get_pixmap(matrix=fitz.Matrix(4,4),alpha=False).save(path.with_suffix('.png'))

