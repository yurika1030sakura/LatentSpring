"""Generate EDM dataset_info for OMol25 from our preprocessed tensors.

Writes configs/omol25_config.py with `omol25_info` (the dataset_info dict EDM's
get_dataset_info expects) computed from the actual processed data: molecule-size
histogram, atom-type counts, max nodes. Pure I/O — no architecture change.

Run with any python that has torch (+ ase for covalent radii):
    python gen_omol25_config.py <processed_dir>
"""
import sys, collections
from pathlib import Path
import torch

ATOM_MAP = [
    "H","He","Li","Be","B","C","N","O","F","Ne","Na","Mg","Al","Si","P","S","Cl","Ar","K","Ca",
    "Sc","Ti","V","Cr","Mn","Fe","Co","Ni","Cu","Zn","Ga","Ge","As","Se","Br","Kr","Rb","Sr","Y","Zr",
    "Nb","Mo","Tc","Ru","Rh","Pd","Ag","Cd","In","Sn","Sb","Te","I","Xe","Cs","Ba","La","Ce","Pr","Nd",
    "Pm","Sm","Eu","Gd","Tb","Dy","Ho","Er","Tm","Yb","Lu","Hf","Ta","W","Re","Os","Ir","Pt","Au","Hg",
    "Tl","Pb","Bi",
]  # contiguous Z = index+1 (1..83)

def main():
    proc = Path(sys.argv[1])
    d = torch.load(proc / "train_data_processed.pt")
    node_idx = d["node_idx_array"]            # (n_mol, 2)
    atom_types = d["atom_types"].long()       # (total_atoms,) indices 0..82
    n_atoms = (node_idx[:, 1] - node_idx[:, 0]).tolist()
    observed = dict(collections.Counter(n_atoms))
    type_counts = dict(collections.Counter(atom_types.tolist()))
    # Dense size prior over the full cap (max_atoms=200): EDM's DistributionNodes
    # keys on exact sizes, so any val/test molecule size must be present. Fill
    # gaps with count 1 so no held-out size triggers a KeyError. (I/O/config.)
    MAX_CAP = 200
    max_n = MAX_CAP
    n_nodes = {n: int(observed.get(n, 1)) for n in range(1, MAX_CAP + 1)}

    try:
        from ase.data import covalent_radii
        radius_dic = [float(covalent_radii[i + 1]) for i in range(len(ATOM_MAP))]
    except Exception:
        radius_dic = [0.77] * len(ATOM_MAP)

    info = {
        "name": "omol25",
        "atom_encoder": {s: i for i, s in enumerate(ATOM_MAP)},
        "atom_decoder": list(ATOM_MAP),
        "atom_z": [i + 1 for i in range(len(ATOM_MAP))],   # nuclear charges
        "n_nodes": {int(k): int(v) for k, v in n_nodes.items()},
        "max_n_nodes": max_n,
        "atom_types": {int(k): int(v) for k, v in type_counts.items()},
        "colors_dic": ["C0"] * len(ATOM_MAP),
        "radius_dic": radius_dic,
        "with_h": True,
    }
    out = Path(__file__).parent / "configs" / "omol25_config.py"
    with open(out, "w") as f:
        f.write("# Auto-generated by gen_omol25_config.py — EDM dataset_info for OMol25.\n")
        f.write("omol25_info = " + repr(info) + "\n")
    print(f"wrote {out}: {len(ATOM_MAP)} elements, max_n_nodes={max_n}, "
          f"{len(n_nodes)} distinct sizes, {len(type_counts)} atom types seen")

if __name__ == "__main__":
    main()
