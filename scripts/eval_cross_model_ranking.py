"""Cross-model energy-ranking evaluation (Q6).

EBMol's central capability claim is that its learned scalar energy
predicts physical strain across samples generated by *other* models.
For BGFM we use the OMol25 energy on each sample (or a learned
scorer the user supplies) and correlate it with GFN2-xTB relaxation
energy across a pooled set of EDM / FlowMol3 / EBMol / BGFM samples.

Input
-----

A directory layout (default, can be flat too):

    samples_dir/
      edm/        samples.json   xtb_relax.csv
      flowmol3/   samples.json   xtb_relax.csv
      ebmol/      samples.json   xtb_relax.csv
      bgfm/       samples.json   xtb_relax.csv

The samples.json files are produced by ``scripts/sample_bgfm.py`` (or
an analogous EBMol / FlowMol3 sampler exported to the same schema).
The xtb_relax.csv files are produced by ``scripts/eval_xtb_relaxation.py``;
they supply the ground-truth strain target.

Per-sample scorer columns can be:

  - ``score_omol25``      OMol25 single-point energy (optional)
  - ``score_bgfm_density`` BGFM density score
                          S(x) = log p_theta(r|c) - beta E_NP - a_phi(c)
  - ``score_bgfm_head``   BGFM scalar energy head output
  - ``score_ebmol``       EBMol learned-energy output

If a samples.json or xtb_relax.csv carries those columns, this script
correlates each with the xTB ΔE_relax and reports Pearson, Spearman,
and AUROC for the top-decile strained set. If only a subset of scorers
exist, the rest are skipped with a note.

Output
------

A single CSV indexed by (model_dir, scorer) with the correlation
numbers and the median ΔE inside the top 10/20/50 percent retained by
each scorer.
"""
from __future__ import annotations

import argparse
import csv
import json
import math
import sys
from pathlib import Path
from typing import Optional


def _load_samples(path: Path) -> list[dict]:
    payload = json.loads(path.read_text())
    if isinstance(payload, list):
        return payload
    if isinstance(payload, dict) and "samples" in payload:
        return payload["samples"]
    raise ValueError(f"unsupported samples JSON shape in {path}")


def _load_xtb_csv(path: Path) -> dict[int, dict]:
    out: dict[int, dict] = {}
    with open(path) as f:
        reader = csv.DictReader(f)
        for row in reader:
            if row.get("index") == "__summary__":
                continue
            try:
                idx = int(row["index"])
            except (KeyError, ValueError):
                continue
            out[idx] = row
    return out


def _to_float(x) -> Optional[float]:
    try:
        v = float(x)
        if math.isnan(v) or math.isinf(v):
            return None
        return v
    except (TypeError, ValueError):
        return None


def _pearson(x: list[float], y: list[float]) -> float:
    n = len(x)
    if n == 0:
        return float("nan")
    mx = sum(x) / n
    my = sum(y) / n
    num = sum((xi - mx) * (yi - my) for xi, yi in zip(x, y))
    dx = math.sqrt(sum((xi - mx) ** 2 for xi in x))
    dy = math.sqrt(sum((yi - my) ** 2 for yi in y))
    return num / (dx * dy) if dx > 0 and dy > 0 else float("nan")


def _rank(values: list[float]) -> list[float]:
    order = sorted(range(len(values)), key=lambda i: values[i])
    ranks = [0.0] * len(values)
    i = 0
    while i < len(order):
        j = i
        while j + 1 < len(order) and values[order[j + 1]] == values[order[i]]:
            j += 1
        avg = (i + j) / 2.0 + 1.0
        for k in range(i, j + 1):
            ranks[order[k]] = avg
        i = j + 1
    return ranks


def _spearman(x: list[float], y: list[float]) -> float:
    if not x:
        return float("nan")
    return _pearson(_rank(x), _rank(y))


def _auroc(scores: list[float], labels: list[int]) -> float:
    if not scores or len(set(labels)) < 2:
        return float("nan")
    order = sorted(range(len(scores)), key=lambda i: scores[i], reverse=True)
    n_pos = sum(labels)
    n_neg = len(labels) - n_pos
    if n_pos == 0 or n_neg == 0:
        return float("nan")
    tp = 0
    fp = 0
    auc = 0.0
    prev_fp = 0
    for idx in order:
        if labels[idx] == 1:
            tp += 1
        else:
            fp += 1
            auc += tp
    auc /= float(n_pos * n_neg)
    return auc


def _correlate_scorer(records: list[dict], target_key: str, scorer_key: str) -> dict:
    pairs = [(r[scorer_key], r[target_key]) for r in records
             if r.get(scorer_key) is not None and r.get(target_key) is not None]
    if not pairs:
        return {"n": 0, "pearson": float("nan"), "spearman": float("nan"),
                "auroc_top10": float("nan"),
                "top10_median_target": float("nan"),
                "top20_median_target": float("nan"),
                "top50_median_target": float("nan")}
    scores = [p[0] for p in pairs]
    targets = [p[1] for p in pairs]
    # Higher score = "less strained" by convention (more negative energy
    # or higher log-density). High-strain = high ΔE; AUROC for the
    # top-decile high-strain set should be HIGH if the scorer is good.
    # We flip the sign so AUROC is in [0, 1] with 1 meaning the scorer
    # correctly assigns low scores to high-strain examples.
    sorted_targets = sorted(targets, reverse=True)
    n = len(targets)
    threshold = sorted_targets[max(0, n // 10 - 1)] if n >= 10 else sorted_targets[0]
    labels_high_strain = [1 if t >= threshold else 0 for t in targets]
    auroc_top = _auroc([-s for s in scores], labels_high_strain)

    def _top_frac_median(frac: float) -> float:
        cutoff = max(1, int(round(n * frac)))
        order = sorted(range(n), key=lambda i: scores[i], reverse=True)
        kept = [targets[i] for i in order[:cutoff]]
        kept.sort()
        return kept[len(kept) // 2] if kept else float("nan")

    return {
        "n": n,
        "pearson": _pearson(scores, targets),
        "spearman": _spearman(scores, targets),
        "auroc_top10": auroc_top,
        "top10_median_target": _top_frac_median(0.10),
        "top20_median_target": _top_frac_median(0.20),
        "top50_median_target": _top_frac_median(0.50),
    }


SCORER_KEYS = ["score_omol25", "score_bgfm_density", "score_bgfm_head", "score_ebmol"]


def _merge_samples_and_xtb(samples: list[dict], xtb_rows: dict[int, dict]) -> list[dict]:
    merged: list[dict] = []
    for i, s in enumerate(samples):
        xtb = xtb_rows.get(i, {})
        rec: dict = {"index": i,
                     "delta_E_kcalmol": _to_float(xtb.get("delta_E_kcalmol")),
                     "max_force_evA": _to_float(xtb.get("max_force_evA"))}
        for key in SCORER_KEYS:
            v = s.get(key)
            if v is None:
                v = xtb.get(key)
            rec[key] = _to_float(v)
        merged.append(rec)
    return merged


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--samples_dir", type=Path, required=True,
                    help="Directory with per-model subdirs each containing "
                         "samples.json and xtb_relax.csv.")
    ap.add_argument("--out_csv", type=Path, required=True)
    ap.add_argument("--target", choices=["delta_E_kcalmol", "max_force_evA"],
                    default="delta_E_kcalmol")
    args = ap.parse_args()

    rows: list[dict] = []
    model_dirs = sorted([p for p in args.samples_dir.iterdir() if p.is_dir()])
    if not model_dirs:
        # Allow flat layout: samples.json + xtb_relax.csv directly in --samples_dir.
        model_dirs = [args.samples_dir]
    for d in model_dirs:
        sj = d / "samples.json"
        xc = d / "xtb_relax.csv"
        if not sj.exists() or not xc.exists():
            print(f"[rank] skipping {d}: missing samples.json or xtb_relax.csv", flush=True)
            continue
        samples = _load_samples(sj)
        xtb_rows = _load_xtb_csv(xc)
        merged = _merge_samples_and_xtb(samples, xtb_rows)
        for scorer in SCORER_KEYS:
            has_any = any(r.get(scorer) is not None for r in merged)
            if not has_any:
                continue
            stats = _correlate_scorer(merged, target_key=args.target, scorer_key=scorer)
            stats.update({"model": d.name, "scorer": scorer, "target": args.target})
            rows.append(stats)

    args.out_csv.parent.mkdir(parents=True, exist_ok=True)
    if not rows:
        print("[rank] no scorer columns found in any model dir; nothing to write.",
              flush=True)
        with open(args.out_csv, "w", newline="") as f:
            csv.writer(f).writerow(["model", "scorer", "target", "n"])
        return 0

    keys = ["model", "scorer", "target", "n",
            "pearson", "spearman", "auroc_top10",
            "top10_median_target", "top20_median_target", "top50_median_target"]
    with open(args.out_csv, "w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=keys)
        writer.writeheader()
        for row in rows:
            writer.writerow({k: row.get(k, "") for k in keys})
    print(f"[rank] wrote {args.out_csv} with {len(rows)} (model, scorer) rows.",
          flush=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
