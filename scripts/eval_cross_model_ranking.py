"""Tier 5: Cross-model energy-ranking benchmark.

EBMol's central capability claim is that its learned scalar energy
predicts physical strain across samples generated by *other* models
(reported Pearson r = 0.65 vs. GFN2-xTB ΔE_relax on EDM-generated mols).

For BGFM we construct a composite scorer

    S(x) = log p_θ^pos(r|c)  -  β · E_OMol25(r,c)  -  a_φ(c)

and evaluate Pearson r / Spearman ρ / AUROC of S(x) versus xTB
ΔE_relax on a pooled set of samples drawn from:
    EDM, FlowMol3, EBMol, BGFM (variants).

Crucially, BGFM cannot self-rank: the test set spans other generators.
This neutralizes the "you trained and you evaluate with OMol25"
criticism.

Status: TEMPLATE.

Usage (planned):

    python scripts/eval_cross_model_ranking.py \
        --bgfm_ckpt runs/.../last.ckpt \
        --bgfm_config configs/.../v8a.yaml \
        --samples_dir runs/eval/cross_model/ \
            (subdirs: edm/, flowmol3/, ebmol/, bgfm/, each containing
             samples.json + xtb_relax.csv produced by previous tiers)
        --out_csv runs/eval/cross_model/ranking.csv

Output: ranking.csv with columns
    [model, n_samples, pearson, spearman, auroc_high_strain, top10pct_dE_xtb]

Target: BGFM's composite scorer beats EBMol's learned-energy scorer
on the same pooled set (Pearson > 0.65).
"""
from __future__ import annotations
import argparse
import sys
from pathlib import Path


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--bgfm_ckpt", type=Path, required=True)
    ap.add_argument("--bgfm_config", type=Path, required=True)
    ap.add_argument("--samples_dir", type=Path, required=True,
                    help="Dir with per-model subdirs: {edm,flowmol3,ebmol,bgfm}/")
    ap.add_argument("--out_csv", type=Path, required=True)
    ap.add_argument("--device", default=None)
    args = ap.parse_args()

    raise NotImplementedError(
        "Tier 5 (cross-model ranking) is scaffolded but not yet wired. "
        "Implementation: "
        "(1) for each model subdir, load samples.json + xtb_relax.csv; "
        "(2) for each sample, compute BGFM scorer S(x) = log p - β·E - a_φ(c); "
        "(3) correlate S vs. xTB ΔE_relax across the pooled set; "
        "(4) report per-model and pooled Pearson r, Spearman ρ, "
        "    AUROC for high-strain detection, top-10% filter ΔE. "
        "Target: pooled Pearson > 0.65 (EBMol's reported number)."
    )


if __name__ == "__main__":
    sys.exit(main())
